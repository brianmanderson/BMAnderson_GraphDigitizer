/**
 * Generates the synthetic e2e fixtures in fixtures/synthetic/: chart PNGs drawn with exact,
 * known geometry, and a ground-truth JSON beside each. Run offline and commit the output:
 *
 *   node scripts/make-synthetic-charts.ts
 *
 * Coordinates in the JSON are image pixels with the app's convention: integer = pixel centre,
 * origin top-left, y down. (On a canvas, pixel centre (i, j) is at (i + 0.5, j + 0.5).)
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'synthetic');

interface Tick {
  label: string;
  /** Data value: a number, or a date string on date axes. */
  value: number | string;
  pos: number;
}

interface ChartSpec {
  name: string;
  description: string;
  width: number;
  height: number;
  title: string;
  xLabel: string;
  yLabel: string;
  xScale: 'linear' | 'date';
  yScale: 'linear' | 'log10';
  /** Pixel row of the X axis line and column of the Y axis line. */
  axisRow: number;
  axisCol: number;
  plotRight: number;
  plotTop: number;
  xTicks: Tick[];
  yTicks: Tick[];
  points: { x: number | string; y: number; px: number; py: number }[];
}

const lerp = (v: number, v0: number, v1: number, p0: number, p1: number) => p0 + ((v - v0) / (v1 - v0)) * (p1 - p0);
const utc = (s: string) => Date.parse(`${s}Z`);

function linearChart(): ChartSpec {
  const [x0, x1, px0, px1] = [0, 10, 80, 600];
  const [y0, y1, py0, py1] = [0, 100, 420, 40];
  const xp = (v: number) => lerp(v, x0, x1, px0, px1);
  const yp = (v: number) => lerp(v, y0, y1, py0, py1);
  const data: [number, number][] = [
    [1, 15],
    [3, 42],
    [4.5, 60],
    [7, 33],
    [9, 88],
  ];
  return {
    name: 'synthetic-linear',
    description: 'Linear X 0–10 and Y 0–100 scatter, 640×480 PNG, axis-aligned. Generated by scripts/make-synthetic-charts.ts.',
    width: 640,
    height: 480,
    title: 'Synthetic scatter (linear)',
    xLabel: 'Dose (mg)',
    yLabel: 'Response (%)',
    xScale: 'linear',
    yScale: 'linear',
    axisRow: py0,
    axisCol: px0,
    plotRight: px1,
    plotTop: py1,
    xTicks: [0, 2, 4, 6, 8, 10].map((v) => ({ label: String(v), value: v, pos: xp(v) })),
    yTicks: [0, 20, 40, 60, 80, 100].map((v) => ({ label: String(v), value: v, pos: yp(v) })),
    points: data.map(([x, y]) => ({ x, y, px: xp(x), py: yp(y) })),
  };
}

function dateLogChart(): ChartSpec {
  const [t0, t1, px0, px1] = [utc('2024-01-01T00:00'), utc('2025-01-01T00:00'), 80, 600];
  const [py0, pyPerDecade] = [420, 120]; // y = 1 at row 420, ×10 every 120 px up
  const xp = (s: string) => lerp(utc(s), t0, t1, px0, px1);
  const yp = (v: number) => py0 - Math.log10(v) * pyPerDecade;
  const quarters = ['2024-01-01', '2024-04-01', '2024-07-01', '2024-10-01', '2025-01-01'];
  const labels = ['Jan 2024', 'Apr', 'Jul', 'Oct', 'Jan 2025'];
  const data: [string, number][] = [
    ['2024-02-29T00:00', 5],
    ['2024-06-15T00:00', 50],
    ['2024-11-20T12:00', 400],
  ];
  return {
    name: 'synthetic-date-log',
    description:
      'Date X (2024, a leap year; ticks at quarter starts, UTC) and log10 Y 1–1000, 640×480 PNG. Generated by scripts/make-synthetic-charts.ts.',
    width: 640,
    height: 480,
    title: 'Synthetic series (date × log₁₀)',
    xLabel: 'Date',
    yLabel: 'Count',
    xScale: 'date',
    yScale: 'log10',
    axisRow: py0,
    axisCol: px0,
    plotRight: px1,
    plotTop: yp(1000),
    xTicks: quarters.map((d, i) => ({ label: labels[i]!, value: d, pos: xp(`${d}T00:00`) })),
    yTicks: [1, 10, 100, 1000].map((v) => ({ label: String(v), value: v, pos: yp(v) })),
    points: data.map(([x, y]) => ({ x, y, px: xp(x), py: yp(y) })),
  };
}

/** Browser-side renderer: draws one ChartSpec onto a canvas and returns a PNG data URL. */
function render(spec: ChartSpec): string {
  const c = document.createElement('canvas');
  c.width = spec.width;
  c.height = spec.height;
  const g = c.getContext('2d')!;
  const at = (v: number) => v + 0.5; // image coordinate (pixel centre) → canvas coordinate
  g.fillStyle = '#fff';
  g.fillRect(0, 0, spec.width, spec.height);

  g.strokeStyle = '#e3e3e3';
  g.lineWidth = 1;
  for (const t of spec.yTicks.slice(1)) {
    g.beginPath();
    g.moveTo(at(spec.axisCol), at(t.pos));
    g.lineTo(at(spec.plotRight), at(t.pos));
    g.stroke();
  }

  g.strokeStyle = '#000';
  g.beginPath();
  g.moveTo(at(spec.axisCol), at(spec.plotTop) - 10);
  g.lineTo(at(spec.axisCol), at(spec.axisRow));
  g.lineTo(at(spec.plotRight) + 10, at(spec.axisRow));
  g.stroke();

  g.fillStyle = '#000';
  g.font = '13px Arial, sans-serif';
  g.textAlign = 'center';
  g.textBaseline = 'top';
  for (const t of spec.xTicks) {
    g.beginPath();
    g.moveTo(at(t.pos), at(spec.axisRow));
    g.lineTo(at(t.pos), at(spec.axisRow) + 6);
    g.stroke();
    g.fillText(t.label, at(t.pos), at(spec.axisRow) + 9);
  }
  g.textAlign = 'right';
  g.textBaseline = 'middle';
  for (const t of spec.yTicks) {
    g.beginPath();
    g.moveTo(at(spec.axisCol) - 6, at(t.pos));
    g.lineTo(at(spec.axisCol), at(t.pos));
    g.stroke();
    g.fillText(t.label, at(spec.axisCol) - 9, at(t.pos));
  }

  g.font = 'bold 15px Arial, sans-serif';
  g.textAlign = 'center';
  g.textBaseline = 'top';
  g.fillText(spec.title, spec.width / 2, 8);
  g.font = '13px Arial, sans-serif';
  g.fillText(spec.xLabel, (spec.axisCol + spec.plotRight) / 2, spec.axisRow + 30);
  g.save();
  g.translate(22, (spec.axisRow + spec.plotTop) / 2);
  g.rotate(-Math.PI / 2);
  g.fillText(spec.yLabel, 0, 0);
  g.restore();

  g.strokeStyle = '#1c5fa8';
  g.lineWidth = 1.5;
  g.beginPath();
  spec.points.forEach((p, i) => (i === 0 ? g.moveTo(at(p.px), at(p.py)) : g.lineTo(at(p.px), at(p.py))));
  g.stroke();
  g.fillStyle = '#d6336c';
  for (const p of spec.points) {
    g.beginPath();
    g.arc(at(p.px), at(p.py), 4, 0, Math.PI * 2);
    g.fill();
  }
  return c.toDataURL('image/png');
}

const browser = await chromium.launch();
const page = await browser.newPage();
mkdirSync(OUT, { recursive: true });
for (const spec of [linearChart(), dateLogChart()]) {
  const dataUrl = await page.evaluate(render, spec);
  writeFileSync(join(OUT, `${spec.name}.png`), Buffer.from(dataUrl.split(',')[1]!, 'base64'));
  const truth = {
    image: `${spec.name}.png`,
    description: spec.description,
    width: spec.width,
    height: spec.height,
    xAxis: { scale: spec.xScale, axisLineRow: spec.axisRow, ticks: spec.xTicks.map((t) => ({ value: t.value, px: t.pos })) },
    yAxis: { scale: spec.yScale, axisLineCol: spec.axisCol, ticks: spec.yTicks.map((t) => ({ value: t.value, py: t.pos })) },
    points: spec.points,
  };
  writeFileSync(join(OUT, `${spec.name}.json`), JSON.stringify(truth, null, 2) + '\n');
  console.log(`wrote ${spec.name}.png and .json`);
}
await browser.close();
