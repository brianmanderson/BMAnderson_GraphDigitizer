/**
 * Axis-detection and auto-calibration benchmark: runs src/auto over the corpus — detection, then
 * tick-label OCR (Tesseract.js) and the suggested calibration — and compares with the baseline.
 *
 *   npm run bench:axes                      run, print, exit 1 on any regression vs baseline.json
 *   npm run bench:axes -- --update          also rewrite baseline.json (only for a deliberate,
 *                                           reviewed change; say why in the commit)
 *   npm run bench:axes -- --verbose         per-image lines
 *   npm run bench:axes -- --only c12,km     a subset (never gates or updates)
 *   npm run bench:axes -- --summary <path>  also write every row of both tables as <path>.csv and
 *                                           <path>.json (bench/summary.ts)
 *
 * Corpus: bench/axes/synthetic/*.json (generated by generate.py) and the figures listed in
 * bench/axes/real/manifest.json. The latest full results go to bench/axes/last-run.json
 * (git-ignored). OCR runs on a pool of Tesseract.js workers with the language data from
 * node_modules (no network); its results are deterministic on a given machine.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';
import { autoCalibrate } from '../../src/auto/index.ts';
import { aggregateCalib, CALIB_GATED, scoreCalibration, VALUE_TOL, type CalibImageScore, type CalibMetrics } from './calib.ts';
import { decodeImage } from './decode.ts';
import { nodeOcrPool } from './ocrNode.ts';
import { aggregate, GATED, scoreImage, type ImageScore, type Metrics } from './score.ts';
import { loadTruth, type Truth } from './truth.ts';
import { asPercent, tableFrom, writeSummary, type Summary, type SummaryColumn } from '../summary.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const BASELINE = join(HERE, 'baseline.json');
const LAST_RUN = join(HERE, 'last-run.json');
const EPS = 1e-9;
const OCR_WORKERS = 4;

interface ImageReport extends Pick<ImageScore, 'tags' | 'boxError'> {
  xError: number | null;
  yError: number | null;
  xTicks: string;
  yTicks: string;
  xCalib?: string;
  yCalib?: string;
  known?: string;
}

interface Report {
  overall: Metrics;
  categories: Record<string, Metrics>;
  calibOverall?: CalibMetrics;
  calibCategories?: Record<string, CalibMetrics>;
  images: Record<string, ImageReport>;
}

function corpus(): Truth[] {
  const synth = join(HERE, 'synthetic');
  const out: Truth[] = readdirSync(synth)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => loadTruth(join(synth, f), 'synthetic'));
  const manifestPath = join(HERE, 'real', 'manifest.json');
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as { figures: { truth: string; tags?: string[] }[] };
  for (const fig of manifest.figures) {
    out.push(loadTruth(resolve(dirname(manifestPath), fig.truth), 'real', fig.tags ?? []));
  }
  return out;
}

const pct = (v: number | null) => (v === null ? '   –  ' : `${(100 * v).toFixed(1).padStart(5)}%`);
const px = (v: number | null) => (v === null ? '   – ' : v.toFixed(2).padStart(5));

function row(name: string, m: Metrics): string {
  return [
    name.padEnd(20),
    String(m.images).padStart(3),
    pct(m.axesFound),
    pct(m.xFound),
    pct(m.yFound),
    px(m.medianAxisError),
    pct(m.boxFound),
    pct(m.tickRecall),
    pct(m.minorRecall),
    pct(m.tickPrecision),
    String(m.falseTicksOnBareAxes).padStart(5),
    m.meanMs.toFixed(0).padStart(5),
  ].join(' ');
}

const HEADER =
  'category               n   axes   x-axis y-axis  err  box    tick-R minor-R tick-P  bare  ms';

function calibRow(name: string, m: CalibMetrics): string {
  return [
    name.padEnd(20),
    pct(m.calibrated),
    pct(m.declined),
    pct(m.correct),
    String(m.wrong).padStart(5),
    String(m.wrongHigh).padStart(6),
    pct(m.scaleAccuracy),
    (m.medianErrorPct === null ? '  –  ' : m.medianErrorPct.toFixed(2)).padStart(6),
    pct(m.autoImages),
    (m.knownMaxError === null ? '   –  ' : m.knownMaxError.toFixed(4)).padStart(7),
    m.meanOcrMs.toFixed(0).padStart(5),
  ].join(' ');
}

const CALIB_HEADER =
  'calibration          calib  declined correct wrong w-high scale   err%   auto    known   ms';

const DETECTION_COLUMNS: SummaryColumn[] = [
  { key: 'images', label: 'images', unit: 'count' },
  { key: 'axesFound', label: 'axes found', unit: '%' },
  { key: 'xFound', label: 'x axis found', unit: '%' },
  { key: 'yFound', label: 'y axis found', unit: '%' },
  { key: 'medianAxisError', label: 'axis line error median', unit: 'px' },
  { key: 'boxFound', label: 'plot box found', unit: '%' },
  { key: 'tickRecall', label: 'tick recall', unit: '%' },
  { key: 'minorRecall', label: 'minor tick recall', unit: '%' },
  { key: 'tickPrecision', label: 'tick precision', unit: '%' },
  { key: 'falseTicksOnBareAxes', label: 'ticks on bare axes', unit: 'count' },
  { key: 'meanMs', label: 'detection time per image', unit: 'ms' },
];
const DETECTION_PERCENT = new Set(['axesFound', 'xFound', 'yFound', 'boxFound', 'tickRecall', 'minorRecall', 'tickPrecision']);

const CALIB_COLUMNS: SummaryColumn[] = [
  { key: 'images', label: 'images', unit: 'count' },
  { key: 'axes', label: 'axes', unit: 'count' },
  { key: 'calibrated', label: 'calibrated', unit: '% of axes' },
  { key: 'declined', label: 'declined', unit: '% of axes' },
  { key: 'correct', label: 'correct', unit: '% of axes' },
  { key: 'wrong', label: 'wrong', unit: 'count' },
  { key: 'wrongHigh', label: 'wrong at high confidence', unit: 'count' },
  { key: 'scaleAccuracy', label: 'scale right', unit: '% of axes with a scale' },
  { key: 'medianErrorPct', label: 'held-out error median of correct axes', unit: '% of axis range' },
  { key: 'autoImages', label: 'images calibrated end to end', unit: '%' },
  { key: 'knownMaxError', label: 'known-value error max', unit: 'data units' },
  { key: 'meanOcrMs', label: 'label finding + OCR per image', unit: 'ms' },
];
const CALIB_PERCENT = new Set(['calibrated', 'declined', 'correct', 'scaleAccuracy', 'autoImages']);

function summaryOf(report: Report, tags: string[]): Summary {
  const detection = tableFrom(
    'detection',
    DETECTION_COLUMNS,
    [['OVERALL', report.overall], ...tags.map((t) => [t, report.categories[t] as Metrics] as [string, Metrics])],
    (m, key) => (DETECTION_PERCENT.has(key) ? asPercent(m[key as keyof Metrics] as number | null) : (m[key as keyof Metrics] as number | null)),
  );
  // The calibration table has no count of its own: n comes from the detection row (2 axes per image).
  type CalibRow = CalibMetrics & { images: number; axes: number };
  const calibRowOf = (c: CalibMetrics, d: Metrics): CalibRow => ({ ...c, images: d.images, axes: 2 * d.images });
  const calibration = tableFrom(
    'calibration',
    CALIB_COLUMNS,
    [
      ['OVERALL', calibRowOf(report.calibOverall as CalibMetrics, report.overall)],
      ...tags.map((t) => [t, calibRowOf(report.calibCategories?.[t] as CalibMetrics, report.categories[t] as Metrics)] as [string, CalibRow]),
    ],
    (m, key) => (CALIB_PERCENT.has(key) ? asPercent(m[key as keyof CalibRow] as number | null) : (m[key as keyof CalibRow] as number | null)),
  );
  return { benchmark: 'bench:axes', generated: new Date().toISOString(), tables: [detection, calibration] };
}

function tickSummary(a: ImageScore['x']): string {
  if (!a.tickMarks) return `bare:${a.detected}`;
  return `${a.matchedMajor}/${a.truthMajor}M ${a.matchedMinor}/${a.truthMinor}m ${a.detectedMatched}/${a.detected}det`;
}

/** Per-axis summary: "ok high linear 0.12%", "WRONG medium linear inf", "low log10". */
function calibSummary(a: CalibImageScore['x']): string {
  if (!a.calibrated) return `${a.level} ${a.scale ?? '-'}`;
  const err = a.maxError === null || !Number.isFinite(a.maxError) ? 'inf' : `${(100 * a.maxError).toFixed(2)}%`;
  return `${a.correct ? 'ok' : 'WRONG'} ${a.level} ${a.scale} ${err}`;
}

async function main(): Promise<number> {
  const args = process.argv.slice(2);
  const update = args.includes('--update');
  const verbose = args.includes('--verbose');
  const onlyArg = args[args.indexOf('--only') + 1];
  const only = args.includes('--only') && onlyArg ? onlyArg.split(',') : null;
  const summaryArg = args[args.indexOf('--summary') + 1];
  const summaryPath = args.includes('--summary') && summaryArg && !summaryArg.startsWith('--') ? summaryArg : null;
  if (args.includes('--summary') && !summaryPath) {
    console.error('--summary needs a path');
    return 2;
  }

  let truths = corpus();
  if (only) truths = truths.filter((t) => only.some((o) => t.id.includes(o)));
  const scores: ImageScore[] = [];
  const calib: CalibImageScore[] = [];
  const started = performance.now();
  const pool = nodeOcrPool(OCR_WORKERS);
  await pool.ready();
  try {
    for (const t of truths) {
      const img = decodeImage(t.imagePath);
      const auto = await autoCalibrate(img, pool, { now: () => performance.now() });
      const det = auto.detection;
      const s = scoreImage(t, det, auto.timings.detectMs);
      scores.push(s);
      const c = scoreCalibration(t, auto, t.knownValues, auto.timings.labelsMs + auto.timings.ocrMs);
      calib.push(c);
      if (verbose) {
        console.log(
          `${t.id.padEnd(24)} x ${px(s.x.error)} ${tickSummary(s.x).padEnd(26)} y ${px(s.y.error)} ${tickSummary(s.y).padEnd(26)} box ${px(s.boxError)} skew ${det.skewDegrees.toFixed(2)}° ${auto.timings.detectMs.toFixed(0)}ms`,
        );
        const lab = (a: typeof auto.x) => a.labels.map((l) => l.text + (l.inlier ? '' : '✗')).join(' ');
        console.log(`${''.padEnd(24)} x ${calibSummary(c.x)} [${lab(auto.x)}]`);
        console.log(`${''.padEnd(24)} y ${calibSummary(c.y)} [${lab(auto.y)}]  ${c.ms.toFixed(0)} ms, ${c.ocrCalls} OCR calls`);
        for (const k of c.known) {
          console.log(`${''.padEnd(24)} known ${k.description}: ${k.expected} → ${k.predicted === null ? '–' : k.predicted.toFixed(4)}`);
        }
      }
    }
  } finally {
    await pool.terminate();
  }

  const tags = [...new Set(scores.flatMap((s) => s.tags))].sort();
  const report: Report = {
    overall: aggregate(scores),
    categories: Object.fromEntries(tags.map((tag) => [tag, aggregate(scores.filter((s) => s.tags.includes(tag)))])),
    calibOverall: aggregateCalib(calib),
    calibCategories: Object.fromEntries(
      tags.map((tag) => [tag, aggregateCalib(calib.filter((_, i) => scores[i]?.tags.includes(tag)))]),
    ),
    images: Object.fromEntries(
      scores.map((s, i) => {
        const c = calib[i] as CalibImageScore;
        return [
          s.id,
          {
            tags: s.tags,
            xError: s.x.error === null ? null : round(s.x.error),
            yError: s.y.error === null ? null : round(s.y.error),
            boxError: s.boxError === null ? null : round(s.boxError),
            xTicks: tickSummary(s.x),
            yTicks: tickSummary(s.y),
            xCalib: calibSummary(c.x),
            yCalib: calibSummary(c.y),
            known: c.known.map((k) => (k.predicted === null ? '–' : k.predicted.toFixed(3))).join(' '),
          },
        ];
      }),
    ),
  };

  console.log(HEADER);
  console.log(row('OVERALL', report.overall));
  for (const tag of tags) console.log(row(tag, report.categories[tag] as Metrics));
  console.log(`\n${CALIB_HEADER}`);
  console.log(calibRow('OVERALL', report.calibOverall as CalibMetrics));
  for (const tag of tags) console.log(calibRow(tag, report.calibCategories?.[tag] as CalibMetrics));
  console.log(`\n${scores.length} images in ${((performance.now() - started) / 1000).toFixed(1)} s (incl. decoding and OCR)`);
  console.log(
    `axes: found = line within 2 px; box: all corners within 4 px; tick-R/minor-R/tick-P: tick recall/precision (2 px along the axis); bare: ticks reported on axes without tick marks`,
  );
  console.log(
    `calib: axes with a medium/high suggestion; declined: axes with none, left to the user (calib + declined = 100%; neither is gated); correct: scale right and every held-out tick within ${100 * VALUE_TOL}% of the axis range (correct + wrong = calib); wrong/w-high: suggested at medium-or-high/high confidence but not correct (should be 0); scale: inferred scale right; err%: median held-out error of correct axes; auto: images calibrated end to end; known: largest error at knownValues (real figures); ms: label finding + OCR per image`,
  );

  if (summaryPath) {
    const out = writeSummary(summaryPath, summaryOf(report, tags));
    console.log(`\nWrote ${out.csv} and ${out.json}`);
  }
  if (only) return 0;
  writeFileSync(LAST_RUN, JSON.stringify(stripMs(report), null, 1) + '\n');
  if (update || !existsSync(BASELINE)) {
    writeFileSync(BASELINE, JSON.stringify(stripMs(report), null, 1) + '\n');
    console.log(`\nWrote ${BASELINE}`);
    return 0;
  }
  return compare(JSON.parse(readFileSync(BASELINE, 'utf8')) as Report, report);
}

function round(v: number): number {
  return Math.round(v * 1000) / 1000;
}

/** Timing varies between machines; keep it out of the committed baseline. */
function stripMs(r: Report): Report {
  const strip = (m: Metrics): Metrics => ({ ...m, meanMs: 0, medianAxisError: m.medianAxisError === null ? null : round(m.medianAxisError) });
  const stripC = (m: CalibMetrics): CalibMetrics => ({ ...m, meanOcrMs: 0, knownMaxError: m.knownMaxError === null ? null : round(m.knownMaxError) });
  return {
    overall: strip(r.overall),
    categories: Object.fromEntries(Object.entries(r.categories).map(([k, m]) => [k, strip(m)])),
    ...(r.calibOverall && { calibOverall: stripC(r.calibOverall) }),
    ...(r.calibCategories && {
      calibCategories: Object.fromEntries(Object.entries(r.calibCategories).map(([k, m]) => [k, stripC(m)])),
    }),
    images: r.images,
  };
}

function compare(base: Report, now: Report): number {
  const problems: string[] = [];
  const check = <M extends object>(name: string, b: M | undefined, n: M, gated: { key: keyof M; higherIsBetter: boolean }[]) => {
    if (!b) return;
    for (const { key, higherIsBetter } of gated) {
      const bv = b[key] as number | null;
      const nv = n[key] as number | null;
      if (bv === null || bv === undefined) continue;
      if (nv === null) {
        problems.push(`${name}: ${String(key)} missing (baseline ${bv})`);
        continue;
      }
      // Rounded like the baseline, so a value equal to it within its precision is no regression.
      const eps = key === 'knownMaxError' ? 5e-4 : EPS;
      if (higherIsBetter ? nv < bv - eps : nv > bv + eps) {
        problems.push(`${name}: ${String(key)} ${fmt(bv)} → ${fmt(nv)}`);
      }
    }
  };
  check('OVERALL', base.overall, now.overall, GATED);
  for (const [tag, m] of Object.entries(now.categories)) check(tag, base.categories[tag], m, GATED);
  for (const tag of Object.keys(base.categories)) {
    if (!now.categories[tag]) problems.push(`category ${tag} disappeared from the corpus`);
  }
  if (base.calibOverall && now.calibOverall) check('calib OVERALL', base.calibOverall, now.calibOverall, CALIB_GATED);
  for (const [tag, m] of Object.entries(now.calibCategories ?? {})) {
    check(`calib ${tag}`, base.calibCategories?.[tag], m, CALIB_GATED);
  }

  // Per-image changes are informational: they explain an aggregate change.
  const changed: string[] = [];
  for (const [id, b] of Object.entries(base.images)) {
    const n = now.images[id];
    if (!n) {
      changed.push(`${id}: missing from this run`);
      continue;
    }
    const diffs = (['xError', 'yError', 'boxError', 'xTicks', 'yTicks', 'xCalib', 'yCalib', 'known'] as const)
      .filter((k) => JSON.stringify(b[k]) !== JSON.stringify(n[k]))
      .map((k) => `${k} ${JSON.stringify(b[k])} → ${JSON.stringify(n[k])}`);
    if (diffs.length) changed.push(`${id}: ${diffs.join(', ')}`);
  }
  if (changed.length) console.log(`\nChanged vs baseline:\n  ${changed.join('\n  ')}`);

  if (problems.length) {
    console.error(`\nREGRESSION vs bench/axes/baseline.json:\n  ${problems.join('\n  ')}`);
    return 1;
  }
  console.log('\nNo regression vs bench/axes/baseline.json.');
  return 0;
}

const fmt = (v: number) => (Number.isInteger(v) ? String(v) : v.toFixed(4));

process.exit(await main());
